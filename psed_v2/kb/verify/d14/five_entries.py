#!/usr/bin/env python3
"""P131b-12b: verify/d14/five_entries.md, for the user's decision on the name, definition and category of every entry with
definition_status: template (the entries made from a free label). Per entry: its yaml fields, then each record keyed to it (fact id,
printed label, value, unit) and the verbatim text of each evidence element (paper, element id, text; elements.texts(), read at run time).
The .md holds paper text: it stays out of git (CLAUDE.md: full text lives outside git); this script is the tracked part.

    python3 psed_v2/verify/d14/five_entries.py
"""
import csv, glob, sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
V2 = HERE.parent.parent
sys.path.insert(0, str(V2 / "pilot"))
import elements  # noqa: E402


def main():
    onto = yaml.safe_load((V2 / "ontology" / "ontology.yaml").read_text(encoding="utf-8"))
    todo = [e for e in onto["entries"] if e.get("definition_status") == "template"]
    keys = {v: k for k, v in elements.PAPERS.items()}
    recs = {e["id"]: [] for e in todo}
    for p in sorted(glob.glob(str(V2 / "pilot" / "10.*.facts.csv"))):
        for r in csv.DictReader(open(p, newline="", encoding="utf-8")):
            if r["quantity"] in recs:
                recs[r["quantity"]].append(r)
    out = ["# The template entries (12b step 5): evidence text for the name, definition and category decision", "",
           "Generated by five_entries.py; holds paper text, not tracked in git.", ""]
    texts = {}
    for e in todo:
        out += [f"## {e['id']}", "", f"- name (printed): `{e.get('name')}`; label `{e.get('label')}`; unit `{e.get('unit', '')}`; role {e.get('role')}; "
                f"category `{e.get('category')}` ({e.get('category_status')})", f"- definition ({e.get('definition_status')}): {e['definition']}", ""]
        seen = set()
        for r in recs[e["id"]]:
            key = r["fact_id"].split(":")[0]
            pid = keys[key]
            out.append(f"- record `{r['fact_id']}` ({r['type']}): printed `{r['label_as_printed']}`, value {r['value'] or r['value_text'] or '-'}"
                       f"{' ' + r['unit'] if r['unit'] else ''}")
            for el in [x for x in r["evidence"].split(";") if x]:
                if (pid, el) in seen:
                    continue
                seen.add((pid, el))
                if pid not in texts:
                    texts[pid] = elements.texts(pid)
                t = " ".join(texts[pid].get(el, "(no text: a panel)").split())
                out.append(f"  - {key} {el}: {t}")
        out.append("")
    (HERE / "five_entries.md").write_text("\n".join(out), encoding="utf-8")
    print(f"{HERE / 'five_entries.md'}: {len(todo)} entries, {sum(len(v) for v in recs.values())} records")


if __name__ == "__main__":
    main()
