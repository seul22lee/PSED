def form_md(form, pass0, onto, F):
    DEFS.clear(); DEFS.update(form["$defs"])
    req = {f: [] for f in form["properties"]}
    for f in form["required"]:
        req[f].append("always")
    for r in form["allOf"]:
        props = r["if"].get("properties", {})
        cond = ("no " + ", ".join(x["required"][0] for x in r["if"]["not"]["anyOf"])) if "not" in r["if"] \
            else " and ".join(f"{key} " + " / ".join(f"`{x}`" for x in props[key].get("enum", [props[key].get("const")])) for key in props)   # P138; P163: every key
        for f in r.get("then", {}).get("required", []):
            req[f].append(f"required when {cond}")
        for f, v in r.get("then", {}).get("properties", {}).items():
            req[f].append(f"forbidden when {cond}" if v is False else f"{_allowed(v)} when {cond}")
        for f, v in r.get("else", {}).get("properties", {}).items():
            req[f].append(f"only when {cond}")
    for f, deps in form.get("dependentRequired", {}).items():
        req[f].append("needs " + ", ".join(deps))
        for d in deps:
            req[d].append(f"required with {f}")
    rows = [(f, _allowed(p), "; ".join(req[f]) or "optional", "extractor" + ("; the compiler joins the list with `;`" if f in JOINED else ""))
            for f, p in form["properties"].items()]
    unnull = lambda p: next((x for x in p.get("anyOf", []) if x.get("type") != "null"), p)       # noqa: E731  P139
    for k, p in unnull(form["properties"]["qualifiers"])["properties"].items():
        rows.append((f"qualifiers.{k}", _allowed(p), "optional", "extractor"))
    for k, p in unnull(form["properties"]["candidate"])["properties"].items():
        rows.append((f"candidate.{k}", _allowed(p), "required with candidate", "extractor"))
    for name, part in pass0["properties"].items():                             # P144: units, table_layouts, panel_layouts
        it = unnull(part)["items"]
        for k, p in it["properties"].items():
            rows.append((f"pass0.{name}.{k}", _allowed(p), "always" if k in it["required"] else "optional", "extractor, pass 0"))
    form_cols = set(form["properties"])
    for c in F.FIELDS:
        if c in COMPILER_ONLY:
            rows.append((c, "not in the form", "", "compiler"))
        elif form_field(c) not in form_cols:
            rows.append((c, "not in the form (facts.FIELDS column with no form field)", "", "nobody"))
    for c, f in FROM_FACTS.items():
        rows.append((c, f"facts.FIELDS column; the form's `{f}`", "", "extractor"))
    esc = lambda x: str(x).replace("|", "\\|")                                  # noqa: E731
    out = ["<!-- GENERATED by psed_v2/ontology/export.py; do not edit -->", "# Extraction form", "", "{FROZEN}", "",
           f"Ontology version {onto['version']}, sha256 `{ontology_hash()}`. Schemas: `form.json` (one record, JSON Schema 2020-12, "
           "additionalProperties false), `form_pass0.json` (one paper's named things). Per-type rules are if/then on `type` in the schema.", "",
           "Out of scope (P133): a statement-only setting or observation (no quantity, value or qualifiers; only method or mentions) is not a form record.", "",
           f"Provider schema (P133, extract/common.py): an enum longer than {PROVIDER_ENUM_MAX} values is sent as a plain string, its ids listed in the prompt; "
           "form.json keeps the enum and the compiler validates against it (P134).", "",
           "Pass-1 groups (P133b, extract/pass1_elements.py): one per section (abstract, s<n>); an element with no section mapping goes to its "
           "container: one group per figure (caption + panels), per table (caption + cells), per equation.", "",
           "| field | allowed values | required when | who fills |", "|---|---|---|---|"]
    out += [f"| {' | '.join(esc(x) for x in r)} |" for r in rows]
    return "\n".join(out) + "\n"


