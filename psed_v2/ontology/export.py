def _allowed(p):
    if p is False:
        return "forbidden"
    if "$ref" in p:
        return _allowed(DEFS[p["$ref"].split("/")[-1]]) + f" ({p['$ref'].split('/')[-1]})"
    if "enum" in p:
        return f"enum, {len(p['enum'])} values" if len(p["enum"]) > 6 else "one of " + ", ".join(f"`{x}`" for x in p["enum"])
    if "const" in p:
        return f"`{p['const']}`"
    if "anyOf" in p:
        return " or ".join(_allowed(x) for x in p["anyOf"])
    if p.get("pattern", "").startswith("^\\S+"):
        n = int(re.search(r"0,(\d+)", p["pattern"]).group(1)) + 1
        return f"string, at most {n} words"
    if "pattern" in p:
        return f"string matching `{p['pattern']}`"
    if p.get("type") == "array":
        return f"list of {_allowed(p['items'])}"
    if p.get("type") == "object" and "additionalProperties" in p and p["additionalProperties"] is not False:
        return f"object: symbol -> {_allowed(p['additionalProperties'])}"
    if "not" in p:                                                              # P158 rule 4: never null
        return "never " + str(p["not"].get("type", "")) if isinstance(p["not"], dict) else "not allowed"
    if p.get("type") == "object" and "properties" not in p:                    # P158 rule 1: an object that must hold some keys
        return "an object holding " + ", ".join(p.get("required", []))
    if p.get("type") == "object":
        return f"object, keys closed ({len(p['properties'])}: {', '.join(p['properties'])})"
    return {"string": "string", "number": "number", "integer": "integer"}.get(p.get("type"), str(p))


