def load():
    onto = yaml.safe_load((HERE / "ontology.yaml").read_text(encoding="utf-8"))
    with (HERE / "pilot_map.csv").open(newline="", encoding="utf-8") as f:
        pmap = list(csv.DictReader(f))
    return onto, pmap


def pending():
    """ontology/pending.csv (P83): provisional extension entries a paper needed and nothing fitted (id, kind quantity | species | structure |
    method | model | mechanism, unit, role, class, definition, citation, cq, paper, records, status). Emitted into the vocabulary
    (ENTRIES carry pending: True while the status is pending; P98: pending_decide.py sets status accepted by rule a, b or c); never frozen."""
    f = HERE / "pending.csv"
    return [r for r in csv.DictReader(f.open(newline="", encoding="utf-8"))] if f.exists() else []


_UNITS = {}


def unit_dimension(unit):
    """A pending quantity's dimension: the dimension of its unit in ontology/units.yaml (P84; '' when the unit is not there)."""
    if not _UNITS:
        for u in yaml.safe_load((HERE / "units.yaml").read_text(encoding="utf-8"))["units"]:
            for v in [u["symbol"]] + list(u["variants"]):
                _UNITS.setdefault(str(v), u["dimension"])
    return _UNITS.get(str(unit), "")


def qualifier_values(q, species=(), materials=(), definitions=()):
    v = q.get("values")
    if isinstance(v, list):
        return sorted(str(x) for x in v)
    if v == "species ids":
        return sorted(species)
    if v == "material ids":
        return sorted(materials)
    if v == "definition ids":                                                   # P108 (b): the definition ids of every entry with definitions
        return sorted(definitions)
    return None                                                                 # an open value (a number, an element symbol, a quantity id)


def unit_tables(onto):
    """P122: lists.UNIT_BASE, UNIT_ALIAS and DIMENSION_OF from ontology/units.yaml: every symbol and variant -> (dimension, factor relative
    to the dimension's canonical unit: the ontology's units: block, else the row with factor 1, else the first row); every variant -> its
    symbol; every dimension -> itself. Never hand-edited again."""
    rows = yaml.safe_load((HERE / "units.yaml").read_text(encoding="utf-8"))["units"]
    by_dim = {}
    for u in rows:
        by_dim.setdefault(u["dimension"], []).append(u)
    canon = {}
    for dim, us in by_dim.items():
        want = str((onto.get("units", {}).get(dim) or {}).get("canonical", "")).split(" ")[0]
        row = next((u for u in us if want and want in [str(u["symbol"])] + [str(v) for v in u["variants"]]), None) \
            or next((u for u in us if float(u["factor"]) == 1.0), us[0])
        canon[dim] = float(row["factor"])
    base, alias = {}, {}
    for u in rows:
        fac = float(u["factor"]) / canon[u["dimension"]]
        for v in [u["symbol"]] + list(u["variants"]):
            base.setdefault(str(v), (u["dimension"], fac))
            if str(v) != str(u["symbol"]):
                alias.setdefault(str(v), str(u["symbol"]))
    return base, alias, {d: d for d in by_dim}


def pending_entry(r):
    """The entry a pending.csv row stands for (P83); merge_pending.py writes the same dict into ontology.yaml when the row is accepted."""
    e = dict(id=r["id"], type=r["kind"] if r["kind"] != "quantity" or r["role"] != "categorical" else "categorical", origin="extension", role=r.get("role", ""),
             definition=r["definition"], unit=r.get("unit", ""), name=r["id"].replace("_", " "), label=r.get("label") or r["id"].replace("_", " "), aliases=[a for a in (r.get("aliases") or "").split("|") if a], pending=r.get("status", "pending") != "accepted",
             dimension=unit_dimension(r.get("unit", "")),
             category={"quantity": "test_structure" if "structure" in (r.get("cq") or "") else "measurement", "model": "models"}.get(r["kind"], ""))
    if r["kind"] == "species":                                                  # a pending species: its formula is its first formula-like alias, else the
        als = [a for a in (r.get("aliases") or "").split("|") if a]             # definition's "(formula X", verbatim (P131b: never derived from the id)
        m = re.search(r"\(formula ([^;)]+)", r["definition"])
        formula = next((a for a in als if re.match(r"^[A-Z][A-Za-z0-9()]*$", a)), "") or (m.group(1).strip() if m else (als[0] if als else ""))
        e.update(kind=r.get("class") or "molecule", formula=formula, aliases=als or ([formula] if formula else []))
    if r["kind"] == "structure":
        e["class"] = r.get("class", "")
    if r["kind"] == "model":
        e.update(model_type=r.get("class", ""), parameters=[], category="models")
    if r.get("converts_to"):                                                    # P109: target|rule|requires
        t, rule, req = (r["converts_to"].split("|") + ["", ""])[:3]
        e["converts_to"] = dict(target=t, rule=rule, requires=req)
    return e


def build(onto, pmap):
    entries = list(onto["entries"])
    voc = onto["vocabularies"]
    pend = pending()
    entries += [pending_entry(r) for r in pend]                                 # P83: pending entries join the vocabulary provisionally
    live = [e for e in entries if not e.get("replaced_by")]
    concepts = sorted(e["id"] for e in live if e["type"] in ("quantity", "categorical") and not e.get("attribute"))
    attributes = sorted(e["id"] for e in live if e["type"] in ("quantity", "categorical") and e.get("attribute"))
    replaced = {e["id"]: e["replaced_by"] for e in entries if e.get("replaced_by")}
    transforms = sorted({t["output"] for t in onto.get("transforms", []) if t["output"] not in ("same",)})
    absorb = sorted(r["pilot_id"] for r in pmap if r["kind"] == "quantity" and r["disposition"] in ("to_absorb", "pending"))   # pending: a disposition recorded, applied in a later step
    absorb_values = {k: sorted(r["pilot_id"] for r in pmap if r["kind"] == k and r["disposition"] == "to_absorb") for k in ("material", "structure", "method")}
    labels = {e["id"]: e.get("label", e["id"]) for e in live if e["type"] in ("quantity", "categorical")}
    names = {e["id"]: e.get("name", e["id"].replace("_", " ")) for e in live if e["type"] in ("quantity", "categorical")}
    for r in pmap:                                                              # provisional labels of the ids still to absorb or pending
        if r["kind"] == "quantity" and r["disposition"] in ("to_absorb", "pending"):
            labels.setdefault(r["pilot_id"], r.get("label") or r["pilot_id"]); names.setdefault(r["pilot_id"], r.get("name") or r["pilot_id"].replace("_", " "))
    species = {e["id"]: dict(formula=e.get("formula", ""), name=e.get("aliases", [e["id"]])[0] if e.get("aliases") else e["id"], kind=e.get("kind", ""),
                             aliases=list(e.get("aliases", [])), material_class=e.get("material_class", ""), ligand_class=e.get("ligand_class", ""))
               for e in live if e["type"] == "species"}
    structures = {e["id"]: dict(cls=e.get("class", ""), aliases=list(e.get("aliases", []))) for e in live if e["type"] == "structure"}
    methods = list(voc["measurement_method"]) + [dict(id=e["id"], **{"class": e.get("class") or e["id"]}, definition=e["definition"]) for e in onto["entries"] if e["type"] == "method"] \
        + [dict(id=r["id"], **{"class": r.get("class") or r["id"]}, definition=r["definition"], pending=r.get("status", "pending") != "accepted") for r in pend if r["kind"] == "method"]   # P131b: merged methods are entries
    defs = {d["id"] for e in live for d in (e.get("definitions") or [])}
    quals = {k: qualifier_values(q, species, [i for i, s in species.items() if s["kind"] == "material"], defs) for k, q in onto["qualifiers"].items()}
    families = {}
    for e in live:
        if e.get("family"):
            families.setdefault(e["family"], []).append(e["id"])
    mechanisms = {e["id"]: dict(name=e.get("name", e["id"].replace("_", " ")), definition=e.get("definition", ""), aliases=list(e.get("aliases", []))) for e in live if e["type"] == "mechanism"}
    kinds = voc.get("kind", {})
    unit_base, unit_alias, dimension_of = unit_tables(onto)                     # P122
    return dict(
        UNIT_BASE=unit_base, UNIT_ALIAS=unit_alias, DIMENSION_OF=dimension_of,
        CONCEPTS=concepts, ATTRIBUTES=attributes, TO_ABSORB=absorb, TRANSFORM_OUTPUTS=transforms, REPLACED=replaced,
        QUANTITIES=sorted(set(concepts) | set(attributes) | set(absorb) | {"other"}),
        LABELS=labels, NAMES=names,
        QUALIFIERS=quals,
        METHODS=sorted({m["id"] for m in methods if not m.get("replaced_by")} | set(absorb_values["method"])),
        OUTPUTS=sorted(e["id"] for e in live if e.get("role") == "output"),
        METHOD_CLASS={m["id"]: m["class"] for m in methods}, METHOD_DEFINITION={m["id"]: m["definition"] for m in methods},
        SPECIES=species,
        MATERIALS=sorted({i for i, s in species.items() if s["kind"] == "material"} | set(absorb_values["material"])),
        STRUCTURES=sorted(set(structures) | set(absorb_values["structure"])), STRUCTURE_CLASS={i: s["cls"] for i, s in structures.items()},
        TO_ABSORB_VALUES=absorb_values,
        FAMILIES=families,
        MECHANISMS=mechanisms, RELATIONS=list(voc.get("relations", [])),
        KINDS=list(kinds) if isinstance(kinds, dict) else list(kinds), PHRASES=dict(kinds) if isinstance(kinds, dict) else {},
        SPECIMEN_CLASSES=list(voc.get("specimen_class", [])),
        AMBIGUOUS=sorted(voc.get("ambiguous_aliases", {})),
        BASES=dict(voc.get("uncertainty_basis", {})),
        ENTRIES={e["id"]: dict(type=e["type"], role=e.get("role", ""), category=e.get("category", ""), definition=e.get("definition", ""), unit=str(e.get("unit", "")),
                               family=e.get("family", ""), qualifiers=list(e.get("qualifiers", [])), aliases=list(e.get("aliases", [])), label=e.get("label", ""),
                               name=e.get("name", ""), attribute=bool(e.get("attribute")), replaced_by=e.get("replaced_by", ""), values_from=e.get("values_from", ""),
                               dimension=e.get("dimension", ""), structure_aliases=list(e.get("structure_aliases", [])), cq=e.get("cq", ""), pending=bool(e.get("pending")),
                               ratio_of=[str(x) for x in e.get("ratio_of", [])], parameters=[str(x) for x in e.get("parameters", [])],   # P101: a model's parameters are card edges
                               definitions=[dict(d) for d in e.get("definitions", [])], converts_to=dict(e["converts_to"]) if e.get("converts_to") else {})   # P108 (b), P109
                 for e in entries},
        HIERARCHY=[dict(id=n["id"], parent=n.get("parent", ""), definition=n["definition"]) for n in onto["hierarchy"]],
        STRUCTURE_CLASSES={c["id"]: dict(parent=c.get("parent") or "", definition=c["definition"], slots=list(c.get("slots", []))) for c in onto.get("structure_classes", [])},   # P78
        CATEGORICAL_VALUES={k: [str(x) for x in voc[k]] for k in voc.get("categorical_conditions", []) if isinstance(voc.get(k), list)},   # the categoricals with a fixed value list
        AMBIGUOUS_ALIASES={a: [str(x) for x in v] for a, v in voc.get("ambiguous_aliases", {}).items()},
        VALUE_ALIASES={k: {str(v): [str(a) for a in al] for v, al in d.items()} for k, d in voc.get("value_aliases", {}).items() if k != "joint"},
        PILOT_MAP={r["pilot_id"]: dict(kind=r["kind"], disposition=r["disposition"], entry_id=r["entry_id"], qualifiers=r["qualifiers"]) for r in pmap},
        PENDING={r["id"]: dict(kind=r["kind"], paper=r["paper"], status=r["status"]) for r in pend},
        FROM_OTHER={lab: e["id"] for e in live for lab in e.get("from_other", [])},   # P131b: printed label -> the entry promoted from the free label other[label]
        TRANSFORMS=[dict(id=t["id"], inputs=[str(x) for x in t["inputs"]], output=str(t["output"]), formula=t.get("formula", "")) for t in onto.get("transforms", [])],   # P84: the A/B label rule reads them
    )


# P132: the extraction form, generated from ontology.yaml + units.yaml + facts.FIELDS + lists.* (nothing hand-written in the schema):
